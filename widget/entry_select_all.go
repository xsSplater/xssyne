package widget

// SelectAll выделяет всё содержимое поля ввода.
//
// Нужен для обработки Ctrl+A на уровне canvas: если пользователь
// приложения перехватывает Ctrl+A своим shortcut'ом (например, чтобы
// «выделить все элементы в таблице»), стандартное поведение Entry
// теряется. Чтобы вернуть его, приложение проверяет фокус и вручную
// вызывает этот метод.
//
// Since: xssyne
func (e *Entry) SelectAll() {
	e.selectAll()
}
